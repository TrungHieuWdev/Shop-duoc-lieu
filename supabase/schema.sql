-- 6. HÀM ĐẶT HÀNG BẢO MẬT PHÍA SERVER (Lớp 4: Chống sửa giá F12 & Chống Spam)
-- ============================================================================
CREATE OR REPLACE FUNCTION public.create_secure_order(
  p_customer_name text,
  p_customer_phone text,
  p_customer_address text,
  p_customer_email text DEFAULT NULL,
  p_customer_note text DEFAULT NULL,
  p_voucher_code text DEFAULT NULL,
  p_items jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_name text := trim(coalesce(p_customer_name, ''));
  v_phone text := regexp_replace(coalesce(p_customer_phone, ''), '\s+', '', 'g');
  v_address text := trim(coalesce(p_customer_address, ''));
  v_email text := NULLIF(trim(coalesce(p_customer_email, '')), '');
  v_note text := NULLIF(trim(coalesce(p_customer_note, '')), '');
  v_voucher text := upper(trim(coalesce(p_voucher_code, '')));
  v_recent_count integer := 0;
  v_item jsonb;
  v_prod record;
  v_qty integer;
  v_subtotal integer := 0;
  v_items_out jsonb := '[]'::jsonb;
  v_default_ship integer := 30000;
  v_free_threshold integer := 350000;
  v_shipping_fee integer := 30000;
  v_total integer := 0;
  v_order_code text;
  v_created_at timestamptz;
BEGIN
  IF char_length(v_name) < 2 OR char_length(v_phone) < 9 OR char_length(v_address) < 5 THEN
    RAISE EXCEPTION 'Thông tin người nhận hàng không hợp lệ.';
  END IF;

  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Giỏ hàng trống.';
  END IF;

  -- Chống spam đơn ảo: tối đa 5 đơn trong 2 phút cho cùng 1 SĐT
  SELECT count(*) INTO v_recent_count
  FROM public.orders
  WHERE customer_phone = v_phone
    AND created_at > now() - interval '2 minutes';

  IF v_recent_count >= 5 THEN
    RAISE EXCEPTION 'Bạn thao tác quá nhanh. Vui lòng thử lại sau ít phút.';
  END IF;

  -- Tự tra cứu giá gốc từ bảng products (chống sửa giá qua F12 DevTools)
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    v_qty := GREATEST(1, LEAST(999, coalesce((v_item->>'quantity')::integer, 1)));

    SELECT id, name, slug, unit, price, thumbnail_url
    INTO v_prod
    FROM public.products
    WHERE id = NULLIF(v_item->>'id', '')::bigint
       OR slug = v_item->>'slug'
    LIMIT 1;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Sản phẩm không tồn tại trong hệ thống.';
    END IF;

    v_subtotal := v_subtotal + (v_prod.price * v_qty);
    v_items_out := v_items_out || jsonb_build_array(
      jsonb_build_object(
        'id', v_prod.id,
        'slug', v_prod.slug,
        'name', v_prod.name,
        'unit', v_prod.unit,
        'price', v_prod.price,
        'quantity', v_qty,
        'thumbnail_url', v_prod.thumbnail_url
      )
    );
  END LOOP;

  -- Lấy phí ship & ngưỡng freeship từ shop_settings
  SELECT default_shipping_fee, free_shipping_threshold
  INTO v_default_ship, v_free_threshold
  FROM public.shop_settings
  WHERE id = 1;

  v_default_ship := coalesce(v_default_ship, 30000);
  v_free_threshold := coalesce(v_free_threshold, 350000);

  IF v_subtotal >= v_free_threshold THEN
    v_shipping_fee := 0;
  ELSIF v_voucher = 'FREESHIP150' AND v_subtotal >= 150000 THEN
    v_shipping_fee := 0;
  ELSIF v_voucher = 'FREESHIP250' AND v_subtotal >= 250000 THEN
    v_shipping_fee := 0;
  ELSIF v_voucher = 'FREESHIP350' AND v_subtotal >= 350000 THEN
    v_shipping_fee := 0;
  ELSE
    v_shipping_fee := v_default_ship;
  END IF;

  v_total := v_subtotal + v_shipping_fee;
  v_order_code := 'NH-' || lpad((floor(random() * 900000) + 100000)::text, 6, '0');

  INSERT INTO public.orders (
    order_code, customer_name, customer_phone, customer_email,
    customer_address, customer_note, payment_method, payment_status,
    order_status, voucher_code, shipping_fee, subtotal, total, items
  )
  VALUES (
    v_order_code, v_name, v_phone, v_email,
    v_address, v_note, 'VIETQR', 'UNPAID',
    'NEW', NULLIF(v_voucher, ''), v_shipping_fee, v_subtotal, v_total, v_items_out
  )
  RETURNING created_at INTO v_created_at;

  RETURN jsonb_build_object(
    'order_code', v_order_code,
    'customer_name', v_name,
    'customer_phone', v_phone,
    'customer_email', v_email,
    'customer_address', v_address,
    'customer_note', v_note,
    'payment_method', 'VIETQR',
    'payment_status', 'UNPAID',
    'order_status', 'NEW',
    'voucher_code', NULLIF(v_voucher, ''),
    'shipping_fee', v_shipping_fee,
    'subtotal', v_subtotal,
    'total', v_total,
    'items', v_items_out,
    'created_at', v_created_at
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_secure_order(text, text, text, text, text, text, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_secure_order(text, text, text, text, text, text, jsonb) TO anon, authenticated;

